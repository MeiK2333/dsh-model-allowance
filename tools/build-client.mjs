/**
 * Build the browser bundle from `src/client/`.
 *
 * DSH loads `client.js` as a lazy CommonJS factory registered with
 * `window.__ModuleLoader__.load`; React and Zod come from the browser's
 * platform module table. esbuild bundles the source and this wrapper supplies
 * the factory envelope around the generated CommonJS body.
 *
 * With `--check` the script builds into memory and fails when the committed
 * `client.js` differs, so CI catches an edited source without a rebuild.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const target = join(root, 'client.js')
const check = process.argv.includes('--check')

const result = await build({
  entryPoints: [join(root, 'src', 'client', 'index.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react', 'zod'],
  legalComments: 'none',
  logLevel: 'silent',
  sourcemap: false,
})

const body = result.outputFiles[0]?.text
if (body === undefined) throw new Error('esbuild produced no output')

const output =
  '/**\n' +
  ' * Generated from src/client by tools/build-client.mjs.\n' +
  ' * Do not edit this file; edit the source modules and run `npm run build`.\n' +
  ' */\n' +
  'window.__ModuleLoader__.load({\n' +
  "  id: 'dsh-model-allowance',\n" +
  '  factory(require) {\n' +
  '    const module = { exports: {} }\n' +
  '    ;(function (module, exports, require) {\n' +
  body +
  '\n    })(module, module.exports, require)\n' +
  '    return module.exports\n' +
  '  },\n' +
  '})\n'

if (check) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // A missing artifact is a failed check, not a crash.
  }
  if (current !== output) {
    console.error('client.js is out of date; run `npm run build`')
    process.exitCode = 1
  } else {
    console.log('client.js is up to date')
  }
} else {
  writeFileSync(target, output)
  console.log(`wrote client.js (${String(output.length)} bytes)`)
}
